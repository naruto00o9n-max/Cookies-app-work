export const guideById = (id: string) => guides.find((g) => g.id === id);
export const guideStorageKey = (userId: string, id: string) =>
  `cookies:guide:v1:${userId}:${id}`;
export function screenGuideId(name: string, params: Record<string, any> = {}) {
  if (name === "Main" || name === "Help") return "";
  if (name === "Detail") return params.work ? "work-detail" : "member-detail";
  if (name === "ControlSection") {
    const key = `control-${params.section}`;
    return guideById(key)
      ? key
      : params.section === "prices"
        ? "specialties"
        : ["months", "archives"].includes(params.section)
          ? "months"
          : "control";
  }
  if (name === "AdminForm")
    return params.kind === "adjustment"
      ? "adjustment"
      : ["addWork", "editWork", "isolate", "customPrice"].includes(params.kind)
        ? "control-works"
        : ["specialty", "reprice"].includes(params.kind)
          ? "specialties"
          : params.kind === "month"
            ? "months"
            : params.kind === "editLast"
              ? "records"
              : params.kind === "settings"
                ? "control-settings"
                : params.kind === "clear"
                  ? "control-data"
                  : "control";
  return (
    (
      {
        Register: "register",
        Finance: "finance",
        Adjustment: "adjustment",
        Control: "control",
        Reports: "reports",
        Specialties: "specialties",
        Months: "months",
        Audit: "audit",
        Diagnostics: "diagnostics",
        Azora: "azora",
        AzoraLink: "azora-link",
        AzoraLinked: "azora-linked",
        AzoraSettings: "azora-settings",
      } as Record<string, string>
    )[name] || ""
  );
}
